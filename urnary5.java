public class urnary5 {
    
    public static void main(String[] args) {
            
        int a = 5;

        System.out.println("First  : " + a++);
        System.out.println("a = " + a);

        System.out.println("Second : " + a++);
        System.out.println("a = " + a);

        System.out.println("Third  : " + ++a);
        System.out.println("a = " + a);

        System.out.println("Fourth : " + a);
    }
}
   